import { OSDElement, PipelineEdge, PipelineNode } from '../types/pipeline';

function hexToBgrTuple(hex: string): string {
  const clean = hex.replace('#', '');
  const full = clean.length === 3 ? clean.split('').map((c) => c + c).join('') : clean;
  const num = parseInt(full, 16);
  if (Number.isNaN(num)) return '(34, 197, 94)';
  const r = (num >> 16) & 255;
  const g = (num >> 8) & 255;
  const b = num & 255;
  return `(${b}, ${g}, ${r})`;
}

export function generatePythonOpenCVCode(nodes: PipelineNode[], edges: PipelineEdge[]): string {
  const lines: string[] = [
    'import cv2',
    'import numpy as np',
    '',
    '# Generated by Vision Studio — OpenCV Pipeline Playground',
    'def run_pipeline(image_path: str):',
  ];

  const nodeMap = new Map(nodes.map((n) => [n.id, n]));
  const incoming = new Map<string, PipelineEdge[]>();
  const adj = new Map<string, string[]>();
  const inDeg = new Map<string, number>();

  nodes.forEach((n) => {
    incoming.set(n.id, []);
    adj.set(n.id, []);
    inDeg.set(n.id, 0);
  });

  edges.forEach((e) => {
    if (nodeMap.has(e.source) && nodeMap.has(e.target)) {
      incoming.get(e.target)!.push(e);
      adj.get(e.source)!.push(e.target);
      inDeg.set(e.target, (inDeg.get(e.target) ?? 0) + 1);
    }
  });

  const queue: string[] = [];
  inDeg.forEach((d, id) => {
    if (d === 0) queue.push(id);
  });

  const varName = (id: string) => `mat_${id.replace(/[^a-zA-Z0-9_]/g, '_')}`;
  let lastVar = 'frame';

  while (queue.length > 0) {
    const id = queue.shift()!;
    const node = nodeMap.get(id)!;
    const outVar = varName(id);
    const inc = incoming.get(id) || [];
    const getIn = (handle: string, fallback = 'frame') => {
      const found = inc.find((e) => e.targetHandle === handle) || inc[0];
      return found ? varName(found.source) : fallback;
    };

    switch (node.type) {
      case 'load_image':
        lines.push(`    ${outVar} = cv2.imread(image_path)  # sample: ${node.params.sampleId ?? 'lena'}`);
        break;
      case 'clahe':
      case 'albu_clahe': {
        const src = getIn('image');
        lines.push(
          `    _lab_${id} = cv2.cvtColor(${src}, cv2.COLOR_BGR2LAB)`,
          `    _l, _a, _b = cv2.split(_lab_${id})`,
          `    _clahe = cv2.createCLAHE(clipLimit=${node.params.clipLimit ?? 2.5}, tileGridSize=(${node.params.tileGridSize ?? 8}, ${node.params.tileGridSize ?? 8}))`,
          `    ${outVar} = cv2.cvtColor(cv2.merge((_clahe.apply(_l), _a, _b)), cv2.COLOR_LAB2BGR)`
        );
        break;
      }
      case 'equalize_hist':
        lines.push(
          `    _ycrcb_${id} = cv2.cvtColor(${getIn('image')}, cv2.COLOR_BGR2YCrCb)`,
          `    _ycrcb_${id}[:, :, 0] = cv2.equalizeHist(_ycrcb_${id}[:, :, 0])`,
          `    ${outVar} = cv2.cvtColor(_ycrcb_${id}, cv2.COLOR_YCrCb2BGR)`
        );
        break;
      case 'brightness_contrast':
        lines.push(
          `    ${outVar} = cv2.convertScaleAbs(${getIn('image')}, alpha=${node.params.contrast ?? 1.15}, beta=${node.params.brightness ?? 15})`
        );
        break;
      case 'gaussian_noise':
        lines.push(
          `    _noise_${id} = np.zeros_like(${getIn('image')}, dtype=np.int16)`,
          `    cv2.randn(_noise_${id}, 0, ${node.params.sigma ?? 22})`,
          `    ${outVar} = np.clip(${getIn('image')}.astype(np.int16) + _noise_${id}, 0, 255).astype(np.uint8)`
        );
        break;
      case 'flip_rotate': {
        const m = String(node.params.mode || 'horizontal');
        if (m === 'rot90') lines.push(`    ${outVar} = cv2.rotate(${getIn('image')}, cv2.ROTATE_90_CLOCKWISE)`);
        else if (m === 'rot180') lines.push(`    ${outVar} = cv2.rotate(${getIn('image')}, cv2.ROTATE_180)`);
        else if (m === 'vertical') lines.push(`    ${outVar} = cv2.flip(${getIn('image')}, 0)`);
        else lines.push(`    ${outVar} = cv2.flip(${getIn('image')}, 1)`);
        break;
      }
      case 'to_hsv':
        lines.push(`    ${outVar} = cv2.cvtColor(${getIn('image')}, cv2.COLOR_BGR2HSV)`);
        break;
      case 'to_lab':
        lines.push(`    ${outVar} = cv2.cvtColor(${getIn('image')}, cv2.COLOR_BGR2LAB)`);
        break;
      case 'colormap':
        lines.push(
          `    _gray_${id} = cv2.cvtColor(${getIn('image')}, cv2.COLOR_BGR2GRAY)`,
          `    ${outVar} = cv2.applyColorMap(_gray_${id}, cv2.COLORMAP_${String(node.params.palette || 'TURBO').toUpperCase()})`
        );
        break;
      case 'to_grayscale':
        lines.push(`    ${outVar} = cv2.cvtColor(${getIn('image')}, cv2.COLOR_BGR2GRAY)`);
        break;
      case 'in_range':
        lines.push(
          `    ${outVar} = cv2.inRange(${getIn('image')}, (${node.params.lowerH ?? 0}, ${node.params.lowerS ?? 40}, ${node.params.lowerV ?? 40}), (${node.params.upperH ?? 180}, ${node.params.upperS ?? 255}, ${node.params.upperV ?? 255}))`
        );
        break;
      case 'gaussian_blur': {
        const k = Math.max(1, Number(node.params.kernelSize ?? 5) | 1);
        lines.push(`    ${outVar} = cv2.GaussianBlur(${getIn('image')}, (${k}, ${k}), ${node.params.sigmaX ?? 1.4})`);
        break;
      }
      case 'median_blur': {
        const k = Math.max(3, Number(node.params.kernelSize ?? 5) | 1);
        lines.push(`    ${outVar} = cv2.medianBlur(${getIn('image')}, ${k})`);
        break;
      }
      case 'bilateral_filter':
        lines.push(
          `    ${outVar} = cv2.bilateralFilter(${getIn('image')}, ${node.params.diameter ?? 7}, ${node.params.sigmaColor ?? 55}, ${node.params.sigmaSpace ?? 35})`
        );
        break;
      case 'box_blur': {
        const k = Math.max(1, Number(node.params.kernelSize ?? 5));
        lines.push(`    ${outVar} = cv2.blur(${getIn('image')}, (${k}, ${k}))`);
        break;
      }
      case 'sobel':
        lines.push(`    ${outVar} = cv2.convertScaleAbs(cv2.Sobel(${getIn('image')}, cv2.CV_16S, 1, 1, ksize=3))`);
        break;
      case 'laplacian':
        lines.push(`    ${outVar} = cv2.convertScaleAbs(cv2.Laplacian(${getIn('image')}, cv2.CV_16S, ksize=3))`);
        break;
      case 'adaptive_threshold': {
        const b = Math.max(3, Number(node.params.blockSize ?? 11) | 1);
        const method =
          node.params.method === 'mean'
            ? 'cv2.ADAPTIVE_THRESH_MEAN_C'
            : 'cv2.ADAPTIVE_THRESH_GAUSSIAN_C';
        lines.push(
          `    _gray_${id} = cv2.cvtColor(${getIn('image')}, cv2.COLOR_BGR2GRAY) if len(${getIn('image')}.shape) == 3 else ${getIn('image')}`,
          `    ${outVar} = cv2.adaptiveThreshold(_gray_${id}, 255, ${method}, cv2.THRESH_BINARY, ${b}, ${node.params.cConstant ?? 4})`
        );
        break;
      }
      case 'otsu_threshold':
        lines.push(
          `    _gray_${id} = cv2.cvtColor(${getIn('image')}, cv2.COLOR_BGR2GRAY)`,
          `    _, ${outVar} = cv2.threshold(_gray_${id}, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)`
        );
        break;
      case 'binary_threshold':
        lines.push(
          `    _gray_${id} = cv2.cvtColor(${getIn('image')}, cv2.COLOR_BGR2GRAY)`,
          `    _, ${outVar} = cv2.threshold(_gray_${id}, ${node.params.thresh ?? 128}, 255, cv2.THRESH_${String(node.params.type || 'BINARY').toUpperCase()})`
        );
        break;
      case 'find_contours': {
        const bgr = hexToBgrTuple(String(node.params.color || '#22C55E'));
        lines.push(
          `    _cnts_${id}, _ = cv2.findContours(${getIn('mask')}, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)`,
          `    ${outVar} = np.zeros((*${getIn('mask')}.shape[:2], 3), dtype=np.uint8)`,
          `    cv2.drawContours(${outVar}, _cnts_${id}, -1, ${bgr}, 1)`
        );
        break;
      }
      case 'corner_detect':
        lines.push(
          `    ${outVar} = ${getIn('image')}.copy()`,
          `    _pts_${id} = cv2.goodFeaturesToTrack(cv2.cvtColor(${getIn('image')}, cv2.COLOR_BGR2GRAY), ${node.params.maxCorners ?? 45}, 0.01, 10)`
        );
        break;
      case 'canny':
        lines.push(`    ${outVar} = cv2.Canny(${getIn('image')}, ${node.params.threshold1 ?? 60}, ${node.params.threshold2 ?? 150})`);
        break;
      case 'dilate': {
        const k = Math.max(1, Number(node.params.kernelSize ?? 3) | 1);
        lines.push(`    ${outVar} = cv2.dilate(${getIn('image')}, np.ones((${k}, ${k}), np.uint8), iterations=${node.params.iterations ?? 1})`);
        break;
      }
      case 'erode': {
        const k = Math.max(1, Number(node.params.kernelSize ?? 3) | 1);
        lines.push(`    ${outVar} = cv2.erode(${getIn('image')}, np.ones((${k}, ${k}), np.uint8), iterations=${node.params.iterations ?? 1})`);
        break;
      }
      case 'morph_open':
      case 'morph_close':
      case 'morph_gradient': {
        const op =
          node.type === 'morph_open'
            ? 'cv2.MORPH_OPEN'
            : node.type === 'morph_close'
              ? 'cv2.MORPH_CLOSE'
              : 'cv2.MORPH_GRADIENT';
        const k = Math.max(3, Number(node.params.kernelSize ?? 3) | 1);
        lines.push(`    ${outVar} = cv2.morphologyEx(${getIn('image')}, ${op}, np.ones((${k}, ${k}), np.uint8))`);
        break;
      }
      case 'apply_mask':
        lines.push(`    ${outVar} = cv2.bitwise_and(${getIn('image')}, ${getIn('image')}, mask=${getIn('mask')})`);
        break;
      case 'bitwise_not':
        lines.push(`    ${outVar} = cv2.bitwise_not(${getIn('image')})`);
        break;
      case 'warp_affine': {
        const src = getIn('image');
        const angle = Number(node.params.angle ?? 18);
        const scale = Number(node.params.scale ?? 0.92);
        const tx = Number(node.params.tx ?? 0);
        const ty = Number(node.params.ty ?? 0);
        const shear = Number(node.params.shearX ?? 0);
        const border = `cv2.BORDER_${String(node.params.borderMode || 'constant').toUpperCase()}`;
        lines.push(
          `    _h_${id}, _w_${id} = ${src}.shape[:2]`,
          `    _M_${id} = cv2.getRotationMatrix2D((_w_${id} / 2, _h_${id} / 2), ${angle}, ${scale})`,
          `    _M_${id}[0, 1] += ${shear}`,
          `    _M_${id}[0, 2] += ${tx}`,
          `    _M_${id}[1, 2] += ${ty}`,
          `    ${outVar} = cv2.warpAffine(${src}, _M_${id}, (_w_${id}, _h_${id}), flags=cv2.INTER_LINEAR, borderMode=${border})`
        );
        break;
      }
      case 'warp_perspective': {
        const src = getIn('image');
        const border = `cv2.BORDER_${String(node.params.borderMode || 'constant').toUpperCase()}`;
        lines.push(
          `    _h_${id}, _w_${id} = ${src}.shape[:2]`,
          `    _src_pts_${id} = np.float32([[0, 0], [_w_${id}, 0], [_w_${id}, _h_${id}], [0, _h_${id}]])`,
          `    _dst_pts_${id} = np.float32([[${Number(node.params.tlX ?? 12) / 100}*_w_${id}, ${Number(node.params.tlY ?? 8) / 100}*_h_${id}], [${Number(node.params.trX ?? 88) / 100}*_w_${id}, ${Number(node.params.trY ?? 12) / 100}*_h_${id}], [${Number(node.params.brX ?? 98) / 100}*_w_${id}, ${Number(node.params.brY ?? 94) / 100}*_h_${id}], [${Number(node.params.blX ?? 2) / 100}*_w_${id}, ${Number(node.params.blY ?? 92) / 100}*_h_${id}]])`,
          `    _H_${id} = cv2.getPerspectiveTransform(_src_pts_${id}, _dst_pts_${id})`,
          `    ${outVar} = cv2.warpPerspective(${src}, _H_${id}, (_w_${id}, _h_${id}), flags=cv2.INTER_LINEAR, borderMode=${border})`
        );
        break;
      }
      case 'face_detect_haar': {
        const src = getIn('image');
        const bgr = hexToBgrTuple(String(node.params.boxColor || '#F43F5E'));
        lines.push(
          `    ${outVar} = ${src}.copy()`,
          `    _cascade_${id} = cv2.CascadeClassifier(cv2.data.haarcascades + 'haarcascade_frontalface_default.xml')`,
          `    _faces_${id} = _cascade_${id}.detectMultiScale(cv2.cvtColor(${src}, cv2.COLOR_BGR2GRAY), scaleFactor=${node.params.scaleFactor ?? 1.1}, minNeighbors=${node.params.minNeighbors ?? 4})`,
          `    for (fx, fy, fw, fh) in _faces_${id}:`,
          `        cv2.rectangle(${outVar}, (fx, fy), (fx + fw, fy + fh), ${bgr}, 2)`
        );
        break;
      }
      case 'face_landmarks': {
        const src = getIn('image');
        lines.push(
          `    ${outVar} = ${src}.copy()`,
          `    # OpenCV Face Landmark / Eye Cascade localization`,
          `    _eye_cascade_${id} = cv2.CascadeClassifier(cv2.data.haarcascades + 'haarcascade_eye.xml')`,
          `    _eyes_${id} = _eye_cascade_${id}.detectMultiScale(cv2.cvtColor(${src}, cv2.COLOR_BGR2GRAY), 1.1, 4)`,
          `    for (ex, ey, ew, eh) in _eyes_${id}:`,
          `        cv2.circle(${outVar}, (ex + ew // 2, ey + eh // 2), ${node.params.pointRadius ?? 3}, ${hexToBgrTuple(String(node.params.landmarkColor || '#38BDF8'))}, -1)`
        );
        break;
      }
      case 'face_skin_mask':
        lines.push(
          `    _ycrcb_${id} = cv2.cvtColor(${getIn('image')}, cv2.COLOR_BGR2YCrCb)`,
          `    ${outVar} = cv2.inRange(_ycrcb_${id}, (40, ${node.params.crMin ?? 133}, ${node.params.cbMin ?? 77}), (255, ${node.params.crMax ?? 175}, ${node.params.cbMax ?? 127}))`
        );
        break;
      case 'ml_kmeans': {
        const src = getIn('image');
        const k = Math.round(Number(node.params.k ?? 5));
        lines.push(
          `    _Z_${id} = ${src}.reshape((-1, 3)).astype(np.float32)`,
          `    _criteria_${id} = (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, ${node.params.attempts ?? 6}, 1.0)`,
          `    _, _lbl_${id}, _ctr_${id} = cv2.kmeans(_Z_${id}, ${k}, None, _criteria_${id}, 4, cv2.KMEANS_PP_CENTERS)`,
          `    ${outVar} = np.uint8(_ctr_${id})[_lbl_${id}.flatten()].reshape(${src}.shape)`
        );
        break;
      }
      case 'ml_svm_segment':
        lines.push(
          `    # OpenCV ML Support Vector Machine pixel classifier`,
          `    _svm_${id} = cv2.ml.SVM_create()`,
          `    _svm_${id}.setType(cv2.ml.SVM_C_SVC)`,
          `    _svm_${id}.setKernel(cv2.ml.SVM_${String(node.params.kernel || 'rbf').toUpperCase()})`,
          `    _svm_${id}.setC(${node.params.cParam ?? 1.5})`,
          `    ${outVar} = ${getIn('image')}.copy()  # train & predict per-pixel features`
        );
        break;
      case 'ml_knn_posterize':
        lines.push(
          `    ${outVar} = cv2.pyrMeanShiftFiltering(${getIn('image')}, sp=${node.params.spatialRadius ?? 4}, sr=${node.params.colorRadius ?? 38})`
        );
        break;
      case 'ml_pca':
        lines.push(
          `    _flat_${id} = ${getIn('image')}.reshape((-1, 3)).astype(np.float32)`,
          `    _mean_${id}, _eig_${id} = cv2.PCACompute(_flat_${id}, mean=None, maxComponents=${node.params.components ?? 1})`,
          `    _proj_${id} = cv2.PCAProject(_flat_${id}, _mean_${id}, _eig_${id})`,
          `    ${outVar} = np.clip(cv2.PCABackProject(_proj_${id}, _mean_${id}, _eig_${id}), 0, 255).astype(np.uint8).reshape(${getIn('image')}.shape)`
        );
        break;
      case 'arithmetic': {
        const op = String(node.params.operation || 'add');
        const a = getIn('a');
        const b = getIn('b');
        if (op === 'blend') {
          const alpha = Number(node.params.alpha ?? 0.65);
          lines.push(`    ${outVar} = cv2.addWeighted(${a}, ${alpha}, ${b}, ${(1 - alpha).toFixed(2)}, 0)`);
        } else if (op === 'bitwise_or') {
          lines.push(`    ${outVar} = cv2.bitwise_or(${a}, ${b})`);
        } else if (op === 'bitwise_and') {
          lines.push(`    ${outVar} = cv2.bitwise_and(${a}, ${b})`);
        } else if (op === 'bitwise_xor') {
          lines.push(`    ${outVar} = cv2.bitwise_xor(${a}, ${b})`);
        } else if (op === 'subtract') {
          lines.push(`    ${outVar} = cv2.subtract(${a}, ${b})`);
        } else if (op === 'absdiff') {
          lines.push(`    ${outVar} = cv2.absdiff(${a}, ${b})`);
        } else {
          lines.push(`    ${outVar} = cv2.add(${a}, ${b})`);
        }
        break;
      }
      case 'draw_histogram':
        lines.push(
          `    # Draw Histogram (${node.params.mode ?? 'channels'}, ${node.params.plotWidth ?? 512}x${node.params.plotHeight ?? 256})`,
          `    ${outVar} = np.zeros((${node.params.plotHeight ?? 256}, ${node.params.plotWidth ?? 512}, 3), dtype=np.uint8)`
        );
        break;
      case 'osd_canvas': {
        const src = getIn('image');
        const els = Array.isArray(node.params.elements) ? (node.params.elements as OSDElement[]) : [];
        lines.push(`    ${outVar} = ${src}.copy()`, `    _h, _w = ${outVar}.shape[:2]`);
        for (const el of els) {
          if (!el.visible) continue;
          const bgr = hexToBgrTuple(el.color);
          const th = el.filled ? -1 : Math.max(1, Math.round(el.thickness || 2));
          if (el.kind === 'rect' || el.kind === 'bbox_label') {
            lines.push(
              `    cv2.rectangle(${outVar}, (int(${el.x.toFixed(3)}*_w), int(${el.y.toFixed(3)}*_h)), (int(${(el.x + el.width).toFixed(3)}*_w), int(${(el.y + el.height).toFixed(3)}*_h)), ${bgr}, ${th}, cv2.LINE_AA)`
            );
            if (el.kind === 'bbox_label' && el.text) {
              lines.push(
                `    cv2.putText(${outVar}, ${JSON.stringify(el.text)}, (int(${el.x.toFixed(3)}*_w), int(${el.y.toFixed(3)}*_h) - 6), cv2.FONT_HERSHEY_SIMPLEX, ${el.fontScale ?? 0.55}, ${bgr}, 1, cv2.LINE_AA)`
              );
            }
          } else if (el.kind === 'circle') {
            lines.push(
              `    cv2.circle(${outVar}, (int(${(el.x + el.width / 2).toFixed(3)}*_w), int(${(el.y + el.height / 2).toFixed(3)}*_h)), int(min(${el.width.toFixed(3)}*_w, ${el.height.toFixed(3)}*_h)/2), ${bgr}, ${th}, cv2.LINE_AA)`
            );
          } else if (el.kind === 'line') {
            lines.push(
              `    cv2.line(${outVar}, (int(${el.x.toFixed(3)}*_w), int(${el.y.toFixed(3)}*_h)), (int(${(el.x2 ?? el.x + el.width).toFixed(3)}*_w), int(${(el.y2 ?? el.y + el.height).toFixed(3)}*_h)), ${bgr}, ${th}, cv2.LINE_AA)`
            );
          } else if (el.kind === 'arrow') {
            lines.push(
              `    cv2.arrowedLine(${outVar}, (int(${el.x.toFixed(3)}*_w), int(${el.y.toFixed(3)}*_h)), (int(${(el.x2 ?? el.x + el.width).toFixed(3)}*_w), int(${(el.y2 ?? el.y + el.height).toFixed(3)}*_h)), ${bgr}, ${th}, cv2.LINE_AA, tipLength=0.22)`
            );
          } else if (el.kind === 'text') {
            lines.push(
              `    cv2.putText(${outVar}, ${JSON.stringify(el.text || 'OSD')}, (int(${el.x.toFixed(3)}*_w), int(${el.y.toFixed(3)}*_h) + 18), cv2.FONT_HERSHEY_SIMPLEX, ${el.fontScale ?? 0.5}, ${bgr}, ${th}, cv2.LINE_AA)`
            );
          } else if (el.kind === 'reticle') {
            lines.push(
              `    cv2.circle(${outVar}, (int(${el.x.toFixed(3)}*_w), int(${el.y.toFixed(3)}*_h)), int(min(${el.width.toFixed(3)}*_w, ${el.height.toFixed(3)}*_h)/2), ${bgr}, ${th}, cv2.LINE_AA)`
            );
          }
        }
        break;
      }
      default:
        lines.push(`    ${outVar} = ${getIn('image')}`);
    }

    lastVar = outVar;
    for (const next of adj.get(id) || []) {
      const nd = (inDeg.get(next) ?? 1) - 1;
      inDeg.set(next, nd);
      if (nd === 0) queue.push(next);
    }
  }

  lines.push(`    return ${lastVar}`, '', "if __name__ == '__main__':", "    out = run_pipeline('input.png')", "    cv2.imwrite('output.png', out)");
  return lines.join('\n');
}
